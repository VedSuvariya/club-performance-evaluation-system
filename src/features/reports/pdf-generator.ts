import { jsPDF } from 'jspdf';

// Page Dimensions for A4: 210mm x 297mm
const PAGE_WIDTH = 210;
const PAGE_HEIGHT = 297;
const MARGIN_LEFT = 15;
const MARGIN_RIGHT = 15;
const CONTENT_WIDTH = PAGE_WIDTH - MARGIN_LEFT - MARGIN_RIGHT;

// Style Tokens
const COLOR_PRIMARY = { r: 30, g: 27, b: 75 }; // Dark Indigo
const COLOR_SECONDARY = { r: 71, g: 85, b: 105 }; // Slate Gray
const COLOR_TEXT = { r: 15, g: 23, b: 42 }; // Dark Charcoal
const COLOR_BORDER = { r: 226, g: 232, b: 240 }; // Light Slate
const COLOR_BG_LIGHT = { r: 248, g: 250, b: 252 }; // Off-white

interface HeaderFooterOptions {
  doc: jsPDF;
  pageNum: number;
}

function drawHeaderFooter({ doc, pageNum }: HeaderFooterOptions) {
  // Top Banner Accent
  doc.setFillColor(COLOR_PRIMARY.r, COLOR_PRIMARY.g, COLOR_PRIMARY.b);
  doc.rect(0, 0, PAGE_WIDTH, 12, 'F');
  
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(255, 255, 255);
  doc.text('CLUB PERFORMANCE EVALUATION AND REPORTING SYSTEM', MARGIN_LEFT, 8);

  // Bottom Footer
  doc.setDrawColor(COLOR_BORDER.r, COLOR_BORDER.g, COLOR_BORDER.b);
  doc.line(MARGIN_LEFT, PAGE_HEIGHT - 15, PAGE_WIDTH - MARGIN_RIGHT, PAGE_HEIGHT - 15);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7);
  doc.setTextColor(COLOR_SECONDARY.r, COLOR_SECONDARY.g, COLOR_SECONDARY.b);
  doc.text('Confidential - Internal Performance Report', MARGIN_LEFT, PAGE_HEIGHT - 10);
  doc.text(`Page ${pageNum}`, PAGE_WIDTH - MARGIN_RIGHT - 10, PAGE_HEIGHT - 10);
}

/**
 * Renders a Member Performance Report PDF.
 */
export function generateMemberReportPDF(data: {
  member: { fullName: string; email: string; clubName: string; joinedAt: string };
  metrics: { totalAssigned: number; totalCompleted: number; completionRate: number; averageRating: number };
  recentEvaluations: { taskTitle: string; rating: number; feedback: string; evaluatorName: string; createdAt: string }[];
  transferHistory: { currentClubName: string; newClubName: string; status: string; decidedAt: string | null; reason: string; comments: string | null }[];
  generatedBy: string;
  generatedAt: string;
}): Buffer {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  let pageNum = 1;
  drawHeaderFooter({ doc, pageNum });

  let y = 25;

  // Title Block
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(COLOR_PRIMARY.r, COLOR_PRIMARY.g, COLOR_PRIMARY.b);
  doc.text('MEMBER PERFORMANCE REPORT', MARGIN_LEFT, y);
  y += 6;

  // Subtitle
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(COLOR_SECONDARY.r, COLOR_SECONDARY.g, COLOR_SECONDARY.b);
  doc.text(`Generated on: ${new Date(data.generatedAt).toLocaleString()}`, MARGIN_LEFT, y);
  doc.text(`Generated by: ${data.generatedBy}`, PAGE_WIDTH - MARGIN_RIGHT - 60, y);
  y += 8;

  // Section: Member Profile Information
  doc.setFillColor(COLOR_BG_LIGHT.r, COLOR_BG_LIGHT.g, COLOR_BG_LIGHT.b);
  doc.rect(MARGIN_LEFT, y, CONTENT_WIDTH, 26, 'F');
  doc.setDrawColor(COLOR_BORDER.r, COLOR_BORDER.g, COLOR_BORDER.b);
  doc.rect(MARGIN_LEFT, y, CONTENT_WIDTH, 26, 'S');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(COLOR_PRIMARY.r, COLOR_PRIMARY.g, COLOR_PRIMARY.b);
  doc.text('MEMBER PROFILE', MARGIN_LEFT + 5, y + 6);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(COLOR_TEXT.r, COLOR_TEXT.g, COLOR_TEXT.b);
  doc.text(`Name: ${data.member.fullName}`, MARGIN_LEFT + 5, y + 13);
  doc.text(`Email: ${data.member.email}`, MARGIN_LEFT + 5, y + 19);
  doc.text(`Current Club: ${data.member.clubName}`, MARGIN_LEFT + 90, y + 13);
  doc.text(`Joined On: ${new Date(data.member.joinedAt).toLocaleDateString()}`, MARGIN_LEFT + 90, y + 19);
  y += 34;

  // Section: Metrics grid
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(COLOR_PRIMARY.r, COLOR_PRIMARY.g, COLOR_PRIMARY.b);
  doc.text('PERFORMANCE METRICS SUMMARY', MARGIN_LEFT, y);
  y += 5;

  const colWidth = CONTENT_WIDTH / 4;
  const metrics = [
    { label: 'Total Assigned', value: data.metrics.totalAssigned.toString() },
    { label: 'Total Completed', value: data.metrics.totalCompleted.toString() },
    { label: 'Completion Rate', value: `${data.metrics.completionRate}%` },
    { label: 'Average Rating', value: data.metrics.averageRating > 0 ? `${data.metrics.averageRating}/5` : 'N/A' },
  ];

  metrics.forEach((metric, index) => {
    const x = MARGIN_LEFT + index * colWidth;
    doc.setFillColor(COLOR_BG_LIGHT.r, COLOR_BG_LIGHT.g, COLOR_BG_LIGHT.b);
    doc.rect(x, y, colWidth - 2, 18, 'F');
    doc.setDrawColor(COLOR_BORDER.r, COLOR_BORDER.g, COLOR_BORDER.b);
    doc.rect(x, y, colWidth - 2, 18, 'S');

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7);
    doc.setTextColor(COLOR_SECONDARY.r, COLOR_SECONDARY.g, COLOR_SECONDARY.b);
    doc.text(metric.label, x + 4, y + 6);

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(COLOR_PRIMARY.r, COLOR_PRIMARY.g, COLOR_PRIMARY.b);
    doc.text(metric.value, x + 4, y + 13);
  });
  y += 26;

  // Section: Recent Evaluations
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(COLOR_PRIMARY.r, COLOR_PRIMARY.g, COLOR_PRIMARY.b);
  doc.text('RECENT TASK EVALUATIONS', MARGIN_LEFT, y);
  y += 5;

  // Table Headers
  doc.setFillColor(COLOR_PRIMARY.r, COLOR_PRIMARY.g, COLOR_PRIMARY.b);
  doc.rect(MARGIN_LEFT, y, CONTENT_WIDTH, 7, 'F');
  
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(7.5);
  doc.setTextColor(255, 255, 255);
  doc.text('DATE', MARGIN_LEFT + 3, y + 4.5);
  doc.text('TASK TITLE', MARGIN_LEFT + 25, y + 4.5);
  doc.text('EVALUATOR', MARGIN_LEFT + 95, y + 4.5);
  doc.text('RATING', MARGIN_LEFT + 135, y + 4.5);
  doc.text('FEEDBACK', MARGIN_LEFT + 152, y + 4.5);
  y += 7;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7.5);
  doc.setTextColor(COLOR_TEXT.r, COLOR_TEXT.g, COLOR_TEXT.b);

  if (data.recentEvaluations.length === 0) {
    doc.setDrawColor(COLOR_BORDER.r, COLOR_BORDER.g, COLOR_BORDER.b);
    doc.rect(MARGIN_LEFT, y, CONTENT_WIDTH, 10, 'S');
    doc.text('No task evaluations recorded.', MARGIN_LEFT + 5, y + 6.5);
    y += 15;
  } else {
    data.recentEvaluations.forEach((evalItem) => {
      // Check for page break
      if (y > PAGE_HEIGHT - 35) {
        doc.addPage();
        pageNum++;
        drawHeaderFooter({ doc, pageNum });
        y = 20;

        // Redraw Headers
        doc.setFillColor(COLOR_PRIMARY.r, COLOR_PRIMARY.g, COLOR_PRIMARY.b);
        doc.rect(MARGIN_LEFT, y, CONTENT_WIDTH, 7, 'F');
        doc.setFont('helvetica', 'bold');
        doc.setFontSize(7.5);
        doc.setTextColor(255, 255, 255);
        doc.text('DATE', MARGIN_LEFT + 3, y + 4.5);
        doc.text('TASK TITLE', MARGIN_LEFT + 25, y + 4.5);
        doc.text('EVALUATOR', MARGIN_LEFT + 95, y + 4.5);
        doc.text('RATING', MARGIN_LEFT + 135, y + 4.5);
        doc.text('FEEDBACK', MARGIN_LEFT + 152, y + 4.5);
        y += 7;
        doc.setFont('helvetica', 'normal');
        doc.setFontSize(7.5);
        doc.setTextColor(COLOR_TEXT.r, COLOR_TEXT.g, COLOR_TEXT.b);
      }

      // Draw Row Border
      doc.setDrawColor(COLOR_BORDER.r, COLOR_BORDER.g, COLOR_BORDER.b);
      doc.line(MARGIN_LEFT, y, PAGE_WIDTH - MARGIN_RIGHT, y);

      const dateStr = new Date(evalItem.createdAt).toLocaleDateString();
      const ratingStr = `${evalItem.rating}/5`;
      const taskTrunc = evalItem.taskTitle.length > 35 ? evalItem.taskTitle.substring(0, 32) + '...' : evalItem.taskTitle;
      const evalTrunc = evalItem.evaluatorName.length > 20 ? evalItem.evaluatorName.substring(0, 17) + '...' : evalItem.evaluatorName;
      const fbTrunc = evalItem.feedback.length > 40 ? evalItem.feedback.substring(0, 37) + '...' : evalItem.feedback;

      doc.text(dateStr, MARGIN_LEFT + 3, y + 5);
      doc.text(taskTrunc, MARGIN_LEFT + 25, y + 5);
      doc.text(evalTrunc, MARGIN_LEFT + 95, y + 5);
      doc.setFont('helvetica', 'bold');
      doc.text(ratingStr, MARGIN_LEFT + 135, y + 5);
      doc.setFont('helvetica', 'normal');
      doc.text(fbTrunc, MARGIN_LEFT + 152, y + 5);

      y += 8;
    });
    // Bottom border of table
    doc.setDrawColor(COLOR_BORDER.r, COLOR_BORDER.g, COLOR_BORDER.b);
    doc.line(MARGIN_LEFT, y, PAGE_WIDTH - MARGIN_RIGHT, y);
    y += 10;
  }

  // Section: Transfer History
  if (y > PAGE_HEIGHT - 45) {
    doc.addPage();
    pageNum++;
    drawHeaderFooter({ doc, pageNum });
    y = 20;
  }

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(COLOR_PRIMARY.r, COLOR_PRIMARY.g, COLOR_PRIMARY.b);
  doc.text('CLUB TRANSFER HISTORY', MARGIN_LEFT, y);
  y += 5;

  // Table Headers
  doc.setFillColor(COLOR_PRIMARY.r, COLOR_PRIMARY.g, COLOR_PRIMARY.b);
  doc.rect(MARGIN_LEFT, y, CONTENT_WIDTH, 7, 'F');
  
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(7.5);
  doc.setTextColor(255, 255, 255);
  doc.text('DECISION DATE', MARGIN_LEFT + 3, y + 4.5);
  doc.text('CURRENT CLUB', MARGIN_LEFT + 30, y + 4.5);
  doc.text('NEW TARGET CLUB', MARGIN_LEFT + 80, y + 4.5);
  doc.text('STATUS', MARGIN_LEFT + 130, y + 4.5);
  doc.text('REASON / COMMENTS', MARGIN_LEFT + 150, y + 4.5);
  y += 7;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7.5);
  doc.setTextColor(COLOR_TEXT.r, COLOR_TEXT.g, COLOR_TEXT.b);

  if (data.transferHistory.length === 0) {
    doc.setDrawColor(COLOR_BORDER.r, COLOR_BORDER.g, COLOR_BORDER.b);
    doc.rect(MARGIN_LEFT, y, CONTENT_WIDTH, 10, 'S');
    doc.text('No club transfer history found.', MARGIN_LEFT + 5, y + 6.5);
  } else {
    data.transferHistory.forEach((transfer) => {
      if (y > PAGE_HEIGHT - 35) {
        doc.addPage();
        pageNum++;
        drawHeaderFooter({ doc, pageNum });
        y = 20;

        // Redraw Headers
        doc.setFillColor(COLOR_PRIMARY.r, COLOR_PRIMARY.g, COLOR_PRIMARY.b);
        doc.rect(MARGIN_LEFT, y, CONTENT_WIDTH, 7, 'F');
        doc.setFont('helvetica', 'bold');
        doc.setFontSize(7.5);
        doc.setTextColor(255, 255, 255);
        doc.text('DECISION DATE', MARGIN_LEFT + 3, y + 4.5);
        doc.text('CURRENT CLUB', MARGIN_LEFT + 30, y + 4.5);
        doc.text('NEW TARGET CLUB', MARGIN_LEFT + 80, y + 4.5);
        doc.text('STATUS', MARGIN_LEFT + 130, y + 4.5);
        doc.text('REASON / COMMENTS', MARGIN_LEFT + 150, y + 4.5);
        y += 7;
        doc.setFont('helvetica', 'normal');
        doc.setFontSize(7.5);
        doc.setTextColor(COLOR_TEXT.r, COLOR_TEXT.g, COLOR_TEXT.b);
      }

      doc.setDrawColor(COLOR_BORDER.r, COLOR_BORDER.g, COLOR_BORDER.b);
      doc.line(MARGIN_LEFT, y, PAGE_WIDTH - MARGIN_RIGHT, y);

      const decisionDate = transfer.decidedAt ? new Date(transfer.decidedAt).toLocaleDateString() : 'N/A';
      const reasonComments = transfer.status === 'REJECTED' ? `${transfer.reason} | Rejection Comments: ${transfer.comments || ''}` : transfer.reason;
      const reasonTrunc = reasonComments.length > 35 ? reasonComments.substring(0, 32) + '...' : reasonComments;

      doc.text(decisionDate, MARGIN_LEFT + 3, y + 5);
      doc.text(transfer.currentClubName, MARGIN_LEFT + 30, y + 5);
      doc.text(transfer.newClubName, MARGIN_LEFT + 80, y + 5);
      doc.setFont('helvetica', 'bold');
      doc.text(transfer.status, MARGIN_LEFT + 130, y + 5);
      doc.setFont('helvetica', 'normal');
      doc.text(reasonTrunc, MARGIN_LEFT + 150, y + 5);

      y += 8;
    });
    doc.setDrawColor(COLOR_BORDER.r, COLOR_BORDER.g, COLOR_BORDER.b);
    doc.line(MARGIN_LEFT, y, PAGE_WIDTH - MARGIN_RIGHT, y);
  }

  return Buffer.from(doc.output('arraybuffer'));
}

