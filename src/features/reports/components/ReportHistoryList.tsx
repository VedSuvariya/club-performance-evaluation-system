'use client';

import Link from 'next/link';
import { DataTable, StatusBadge } from '@/components/dashboard/components';
import { FileText, Download, Eye } from 'lucide-react';
import { ReportRecord } from '@/lib/database/reports';

interface ReportHistoryListProps {
  reports: ReportRecord[];
  basePath: 'member' | 'department-lead' | 'club-president' | 'swc';
}

export function ReportHistoryList({ reports, basePath }: ReportHistoryListProps) {
  const columns = [
    {
      header: 'Report Type',
      accessor: (r: ReportRecord) => (
        <div className="flex items-center gap-3">
          <FileText className="h-5 w-5 text-indigo-500 shrink-0" />
          <span className="font-semibold text-slate-900 dark:text-white">
            {r.reportType === 'MEMBER_EVALUATION' ? 'Member Evaluation' : 'Club Summary'}
          </span>
        </div>
      ),
    },
    {
      header: 'Target Subject',
      accessor: (r: ReportRecord) => (
        <span className="text-slate-700 dark:text-slate-300">
          {r.reportType === 'MEMBER_EVALUATION'
            ? r.targetUser?.fullName || 'Unknown Member'
            : r.targetClub?.name || 'Unknown Club'}
        </span>
      ),
    },
    {
      header: 'Generated By',
      accessor: (r: ReportRecord) => (
        <span className="text-slate-600 dark:text-slate-400">
          {r.generator?.fullName || 'System'}
        </span>
      ),
    },
    {
      header: 'Date Generated',
      accessor: (r: ReportRecord) => (
        <span className="text-xs text-slate-500 dark:text-slate-400">
          {new Date(r.createdAt).toLocaleString()}
        </span>
      ),
    },
    {
      header: 'Status',
      accessor: (r: ReportRecord) => {
        let type: 'success' | 'warning' | 'error' | 'neutral' = 'neutral';
        const status = r.status?.toUpperCase();
        if (status === 'COMPLETED') type = 'success';
        if (status === 'GENERATING') type = 'warning';
        if (status === 'FAILED') type = 'error';
        return <StatusBadge label={r.status} type={type} />;
      },
    },
    {
      header: 'Actions',
      accessor: (r: ReportRecord) => {
        const status = r.status?.toUpperCase();
        return (
          <div className="flex items-center gap-3">
            {status === 'COMPLETED' ? (
              <>
                <Link
                  href={`/${basePath}/reports/${r.id}`}
                  className="inline-flex items-center gap-1 text-xs font-semibold text-indigo-600 dark:text-indigo-400 hover:text-indigo-800 dark:hover:text-indigo-300 transition-colors"
                  title="View Report Preview"
                >
                  <Eye className="h-3.5 w-3.5" />
                  View
                </Link>
                <a
                  href={`/api/reports/${r.id}/download`}
                  className="inline-flex items-center gap-1 text-xs font-semibold text-slate-600 dark:text-slate-400 hover:text-slate-800 dark:hover:text-slate-200 transition-colors"
                  title="Download PDF"
                >
                  <Download className="h-3.5 w-3.5" />
                  Download
                </a>
              </>
            ) : status === 'FAILED' ? (
              <span className="text-xs text-rose-500 font-medium">Generation Failed</span>
            ) : (
              <span className="text-xs text-amber-500 font-medium animate-pulse">Generating...</span>
            )}
          </div>
        );
      },
    },
  ];

  return (
    <div className="space-y-4">
      <DataTable
        columns={columns}
        data={reports}
        emptyText="No reports generated yet. Use the tool above to generate a new report."
      />
    </div>
  );
}
